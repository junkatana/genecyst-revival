#!/usr/bin/env python3
"""Extract the animated blood-drip border under the Genecyst menu bar.
Inputs: N native-resolution crops of the strip (248 px wide, rows starting right
below the menu bar), one per animation state, in cycle order. Output: C source
with three 1-bit masks (bright red / dark red / light highlight) per frame."""
import sys
from PIL import Image
files, out = sys.argv[1:-1], sys.argv[-1]
W, H = 248, 24
def cls(p):
    r, g, b = p[:3]
    if r > 220 and g > 60: return 3    # light highlight #ED5355 ("reflection")
    if r > 170 and g < 50: return 1    # bright red  #C31411
    if r > 100 and g < 40: return 2    # dark red    #950D10
    return 0
frames = []
for fn in files:
    im = Image.open(fn).convert('RGB'); px = im.load()
    frames.append([[cls(px[x, y]) if x < im.width and y < im.height else 0 for x in range(W)] for y in range(H)])
with open(out, 'w') as f:
    f.write('/* Generated by tools/extract_drip.py. Do not edit. */\n#include <stdint.h>\n')
    f.write('const int drip_w = %d, drip_h = %d, drip_frames = %d;\n' % (W, H, len(frames)))
    for name, v in (('drip_bright', 1), ('drip_dark', 2), ('drip_light', 3)):
        f.write('const uint8_t %s[%d][%d][%d] = {\n' % (name, len(frames), H, (W + 7) // 8))
        for fr in frames:
            f.write(' {\n')
            for line in fr:
                bs = []
                for bx in range(0, W, 8):
                    b = 0
                    for i in range(8):
                        if bx + i < W and line[bx + i] == v: b |= 1 << i
                    bs.append(b)
                f.write('  {%s},\n' % ','.join('0x%02x' % b for b in bs))
            f.write(' },\n')
        f.write('};\n')
print('frames:', len(frames))
