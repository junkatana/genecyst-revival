#!/usr/bin/env python3
"""Extract the GUI bitmaps embedded in GENECYST.EXE (the "DSL" resource
container: VGA palette + ".r2" run-length images) and write them as C tables.

usage: extract_exe_resources.py GENECYST.EXE src/gui/res_data.c
.r2 layout: u32 1, u32 size, u32 w, u32 h, u32 row_offset[h]; each row is a
sequence of (skip, count, count pixel bytes) until the row is full."""
import re, struct, sys

exe, out = sys.argv[1], sys.argv[2]
data = open(exe, 'rb').read()
chunks = []
for m in re.finditer(rb'DSL\x00', data):
    off = m.start()
    typ = data[off + 4]
    size = struct.unpack_from('<I', data, off + 5)[0]
    name = data[off + 9:off + 18].split(b'\0')[0].decode(errors='replace')
    chunks.append((name, typ, data[off + 18:off + 18 + size]))

pal = None
for name, typ, body in chunks:
    if name == 'bg.lbm':
        pal = [tuple(round(v * 255 / 63) for v in body[i * 3:i * 3 + 3]) for i in range(256)]

def decode_r2(body):
    _, size, w, h = struct.unpack_from('<4I', body, 0)
    offs = struct.unpack_from('<%dI' % h, body, 16)
    img = [[255] * w for _ in range(h)]
    for y in range(h):
        pos, x = offs[y], 0
        end = offs[y + 1] if y + 1 < h else size
        while x < w and pos < end:
            x += body[pos]; pos += 1
            if x >= w or pos >= end: break
            n = body[pos]; pos += 1
            for _ in range(n):
                if x < w: img[y][x] = body[pos]
                pos += 1; x += 1
    return w, h, img

images = {}
for name, typ, body in chunks:
    if typ == 2:
        images[name.replace('.r2', '')] = decode_r2(body)

with open(out, 'w') as f:
    f.write('/* Generated by tools/extract_exe_resources.py from GENECYST.EXE. Do not edit. */\n')
    f.write('#include "res_data.h"\n\n')
    f.write('const uint32_t res_palette[256] = {\n')
    for i in range(0, 256, 8):
        f.write('    ' + ', '.join('0x%02X%02X%02X' % pal[j] for j in range(i, i + 8)) + ',\n')
    f.write('};\n\n')
    for name, (w, h, img) in images.items():
        f.write('static const uint8_t px_%s[%d] = {\n' % (name, w * h))
        for row in img:
            f.write('    ' + ','.join('%3d' % p for p in row) + ',\n')
        f.write('};\n')
    f.write('\nconst ResImage res_images[] = {\n')
    for name, (w, h, img) in images.items():
        f.write('    { "%s", %d, %d, px_%s },\n' % (name, w, h, name))
    f.write('};\nconst int res_image_count = %d;\n' % len(images))
print('images:', ', '.join('%s %dx%d' % (n, w, h) for n, (w, h, _) in images.items()))
