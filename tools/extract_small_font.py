#!/usr/bin/env python3
"""Extract the small upper-case Genecyst GUI font (5 rows, proportional) from
native 320x240 screenshots of the original. Each region lists the known text
lines top->bottom; glyphs are split on blank columns and matched 1:1 with the
non-space characters. Writes src/gui/font_small_data.c."""
import sys
from collections import Counter, defaultdict
from PIL import Image

H = 5
SHOTS = 'reference/original/screenshots/explore/'
# (file, x0, y0, x1, y1, lines)
REGIONS = [
    ('22_dlg_messages.png', 23, 27, 258, 137, [
        'VESA VERSION 2.0 DETECTED', 'S3 INCORPORATED. TRIO64', 'VESA MODE SET: 320X240X8 BANKED',
        'YM2612 FM INITIALIZED (2048K)', '68000 CPU BUILT', '1536K READ (BINARY)', 'NAME: SAMPLE PROGRAM',
        'SRAM: 200000 - 20FFFF (ODD)', '68000 RESET', 'Z80 RESET', 'VDP RESET', 'CPU EMULATION STARTED']),
    ('20_cpu_dump_sub.png', 178, 90, 272, 202, [
        'RAM', 'ROM', 'VRAM', 'VSRAM', 'CRAM', 'Z80 RAM', 'YM2612 REGS', 'MESSAGES', 'VDP BASE', 'VDP REGS', 'SPRITES']),
    ('27_dlg_about.png', 24, 32, 236, 64, [
        'GENECYST DOS VX.XX', 'WATCOM C++ 10.60 DEC 25 1997 06:66:00', 'COPYRIGHT (C) 1998 BLOODLUST SOFTWARE']),
    ('32_dlg_timing.png', 48, 32, 112, 78, ['HBLANK INST:', 'VBLANK INST:', 'VIRTUAL FPS:']),
    ('31_dlg_input1.png', 24, 30, 82, 38, ['INPUT TYPE:']),
    ('31_dlg_input1.png', 144, 30, 198, 38, ['TEST AREA:']),
    ('14_view_layer_sub.png', 117, 103, 212, 162, [
        'SCROLL B LOW', 'SCROLL A LOW', 'SCROLL B HIGH', 'SCROLL A HIGH', 'SPRITES', 'WINDOW']),
    ('10_settings_resolution_sub.png', 238, 20, 305, 120, [
        '256X224', '256X240', '256X256 F11', '320X200', '320X224', '320X240 F12', '384X257', '640X400', '640X480', 'OTHER...']),
    ('28_dlg_directories.png', 28, 32, 64, 88, ['SAVE:', 'PCX:', 'LOG:', 'PATCH:']),
    ('21_settings_version_sub.png', 184, 38, 216, 72, ['USA', 'JAPAN', 'EUROPE']),
    ('30_dlg_other_res.png', 70, 72, 106, 96, ['X-RES:', 'Y-RES:']),
    ('11_settings_input_sub.png', 234, 10, 290, 32, ['DEVICE 1', 'DEVICE 2']),
    ('16_sound_rate_sub.png', 236, 10, 290, 42, ['11025', '22050', '44100']),
]

def is_text(p):
    r, g, b = p[:3]
    if max(r, g, b) < 110: return False
    if r > g + 60 and r > b + 60: return False        # red background shades
    if g > 140 and r < 40 and b < 40: return False     # pure selection green (0,168,0)
    return True

def bands(px, x0, x1, y0, y1):
    rows = [y for y in range(y0, y1) if any(is_text(px[x, y]) for x in range(x0, x1))]
    out, cur = [], []
    for y in rows:
        if cur and y - cur[-1] > 1: out.append(cur); cur = []
        cur.append(y)
    if cur: out.append(cur)
    return out

def segments(px, x0, x1, ytop):
    cols = [any(is_text(px[x, y]) for y in range(ytop, ytop + H)) for x in range(x0, x1)] + [False]
    segs, start = [], None
    for i, c in enumerate(cols):
        if c and start is None: start = i
        if not c and start is not None: segs.append((x0 + start, x0 + i)); start = None
    return segs

def bits(px, xa, xb, ytop):
    rows = []
    for y in range(ytop, ytop + H):
        v = 0
        for i, x in enumerate(range(xa, xb)):
            if is_text(px[x, y]): v |= 1 << i
        rows.append(v)
    return tuple(rows)

votes = defaultdict(Counter)
spaces = Counter()
for fn, x0, y0, x1, y1, lines in REGIONS:
    im = Image.open(SHOTS + fn).convert('RGB'); px = im.load()
    bs = bands(px, x0, x1, y0, y1)
    if len(bs) != len(lines):
        print(f'!! {fn}: {len(bs)} bands, {len(lines)} lines expected', [(b[0], b[-1]) for b in bs]); continue
    for b, text in zip(bs, lines):
        ytop = b[0]
        if len(b) != H: print(f'   {fn} "{text}": band height {len(b)}'); 
        segs = segments(px, x0, x1, ytop)
        chars = [c for c in text if c != ' ']
        if len(segs) != len(chars):
            print(f'!! {fn} "{text}": {len(segs)} segments vs {len(chars)} chars'); 
            for xa, xb in segs: print('     seg', xa, xb)
            continue
        for (xa, xb), ch in zip(segs, chars):
            votes[ch][bits(px, xa, xb, ytop)] += 1
        # space width: gap between segments around spaces
        for i, ch in enumerate(text):
            if ch == ' ':
                k = len([c for c in text[:i] if c != ' '])
                spaces[segs[k][0] - segs[k - 1][1]] += 1
print('space gaps:', spaces.most_common(4))
print('glyphs:', ''.join(sorted(votes)))
for ch in sorted(votes):
    c = votes[ch]
    if len(c) > 1: print(f'  {ch!r}: variants {c.most_common(3)}')
out = ['/* font_small_data.c -- generated by tools/extract_small_font.py from screenshots of the original */',
       '#include "font.h"', '', 'const FontGlyph font_small_glyphs[] = {']
for ch in sorted(votes):
    rows, _ = votes[ch].most_common(1)[0]
    w = max(r.bit_length() for r in rows)
    out.append('    { 0x%02X, %d, { %s } }, /* %s */' % (ord(ch), w, ', '.join('0x%02X' % r for r in rows), ch.replace('*/', '* /')))
out.append('};')
out.append('const int font_small_count = sizeof font_small_glyphs / sizeof font_small_glyphs[0];')
open('src/gui/font_small_data.c', 'w').write('\n'.join(out) + '\n')
print('wrote', len(votes), 'glyphs')
